-- Every colour comes from lua/theme.lua, which Nix generates from the theme
-- selected in vars.nix (themes/*.nix) - the same palette kitty, waybar, dunst
-- and rofi use. Nothing here should contain a hex literal.

local loaded, theme = pcall(require, "theme")
if not loaded then
	vim.notify(
		"colorscheme 'dotfiles': lua/theme.lua is missing - rebuild with home-manager",
		vim.log.levels.ERROR
	)
	return
end

